"""Build the transparent standalone script from its ordered source sections."""
from __future__ import annotations

import argparse
import ast
from pathlib import Path
import sys


SECTIONS = ("imports", "config", "files", "processing", "browser", "worker", "main")
ARTIFACT_NAME = "ctrip_flights_scraper.py"


class BuildError(ValueError):
    """The source sections violate the standalone distribution contract."""


def _target_names(node):
    if isinstance(node, ast.Name):
        yield node.id
    elif isinstance(node, (ast.List, ast.Tuple)):
        for item in node.elts:
            yield from _target_names(item)


def _top_names(node):
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        yield node.name
    elif isinstance(node, ast.Assign):
        for target in node.targets:
            yield from _target_names(target)
    elif isinstance(node, ast.AnnAssign):
        yield from _target_names(node.target)


def _is_main_guard(node):
    return (isinstance(node, ast.If) and isinstance(node.test, ast.Compare)
            and isinstance(node.test.left, ast.Name) and node.test.left.id == "__name__"
            and len(node.test.ops) == 1 and isinstance(node.test.ops[0], ast.Eq)
            and len(node.test.comparators) == 1
            and isinstance(node.test.comparators[0], ast.Constant)
            and node.test.comparators[0].value == "__main__")


def validate_source(source: str, root: Path) -> None:
    try:
        tree = ast.parse(source, filename=ARTIFACT_NAME)
        compile(tree, ARTIFACT_NAME, "exec")
    except SyntaxError as exc:
        raise BuildError(f"Generated script has invalid syntax: {exc}") from exc
    owners = {}
    for node in tree.body:
        for name in _top_names(node):
            if name in owners:
                raise BuildError(f"Duplicate top-level name {name!r} at lines {owners[name]} and {node.lineno}")
            owners[name] = node.lineno
    guards = [node for node in ast.walk(tree) if _is_main_guard(node)]
    if len(guards) != 1 or guards[0] not in tree.body:
        raise BuildError("The script must contain exactly one top-level __main__ guard")
    local_names = {*SECTIONS, "crawler", "source_sections", "scripts"}
    local_names.update(p.stem for p in root.glob("*.py") if p.name != ARTIFACT_NAME)
    local_names.update(p.name for p in root.iterdir() if p.is_dir() and (p / "__init__.py").exists())
    for node in ast.walk(tree):
        imported = []
        if isinstance(node, ast.ImportFrom):
            if node.level:
                raise BuildError(f"Relative project import at line {node.lineno}")
            imported = [(node.module or "").split(".")[0]]
        elif isinstance(node, ast.Import):
            imported = [item.name.split(".")[0] for item in node.names]
        for name in imported:
            if name in local_names:
                raise BuildError(f"Repository-dependent import {name!r} at line {node.lineno}")
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in {"exec", "eval", "__import__"}:
            raise BuildError(f"Dynamic source execution at line {node.lineno}")


def build_source(root: Path) -> str:
    blocks = ["# Generated by scripts/build_single_file.py; edit source_sections for repository changes.\n"]
    for name in SECTIONS:
        path = root / "source_sections" / f"{name}.py.inc"
        if not path.is_file():
            raise BuildError(f"Missing required source section: {path.relative_to(root)}")
        section = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").rstrip()
        blocks.append(f"\n# {'=' * 16} {name} {'=' * 16}\n{section}\n")
    result = "".join(blocks)
    validate_source(result, root)
    return result


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1], help="Repository root")
    parser.add_argument("--check", action="store_true", help="Check the committed artifact without modifying it")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        content = build_source(root).encode("utf-8")
        target = root / ARTIFACT_NAME
        if args.check:
            if not target.is_file() or target.read_bytes() != content:
                raise BuildError("Standalone script is missing or differs from source sections; rebuild it")
            print(f"PASS {ARTIFACT_NAME} matches source sections")
        else:
            temporary = target.with_suffix(".py.tmp")
            temporary.write_bytes(content)
            temporary.replace(target)
            print(f"Built {ARTIFACT_NAME} ({len(content)} bytes)")
    except (BuildError, OSError) as exc:
        print(f"Build failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
